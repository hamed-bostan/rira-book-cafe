import fs from "fs";
import path from "path";

import { typography as typographyPrimitives } from "../tokens/primitives/typography";
import { colors } from "../tokens/semantic/colors";
import { radius as semanticRadius } from "../tokens/semantic/radius";
import { shadow as semanticShadow } from "../tokens/semantic/shadow";
import { typography as semanticTypography } from "../tokens/semantic/typography";

const toKebab = (str: string) =>
  str
    .replace(/_/g, "-")
    .replace(/([a-z])([A-Z])/g, "$1-$2")
    .toLowerCase();

const createNestedVars = (prefix: string, obj: Record<string, unknown>, pathArr: string[] = []): string[] => {
  const vars: string[] = [];

  for (const [key, value] of Object.entries(obj)) {
    const isDefault = key === "DEFAULT";
    const currentPath = isDefault ? pathArr : [...pathArr, toKebab(key)];

    if (typeof value === "object" && value !== null && !Array.isArray(value)) {
      vars.push(...createNestedVars(prefix, value as Record<string, unknown>, currentPath));
    } else {
      const segments = [prefix, ...currentPath].filter(Boolean);
      const varName = `--${segments.join("-")}`;
      vars.push(`${varName}: ${String(value)};`);
    }
  }

  return vars;
};

// `Object.entries` can't preserve the per-group value shape of the `as const`
// token tree below (TS falls back to its untyped overload), so we pin the
// shape once here instead of leaking `any` into every entry.
type TypographyToken = { size?: string; lineHeight?: string; weight?: string | number; family?: string };

const buildTypographyTokens = () => {
  const vars: string[] = [];

  for (const [group, variants] of Object.entries(semanticTypography)) {
    for (const [variant, token] of Object.entries(variants) as [string, TypographyToken][]) {
      const name = `${toKebab(group)}-${toKebab(variant)}`;

      if (token.size) vars.push(`--text-${name}: ${token.size};`);

      if (token.lineHeight) vars.push(`--text-${name}--line-height: ${token.lineHeight};`);

      if (token.weight) vars.push(`--text-${name}--font-weight: ${token.weight};`);

      if (token.family) vars.push(`--text-${name}--font-family: ${token.family};`);
    }
  }

  return vars;
};

const themeVars = [
  // Primitive typography tokens
  // Font families use Tailwind v4's `--font-*` namespace (so `sans` → `--font-sans`,
  // which powers the `font-sans` utility and `var(--font-sans)`).
  ...createNestedVars("font", typographyPrimitives.fontFamily ?? {}),
  ...createNestedVars("font-weight", typographyPrimitives.fontWeight ?? {}),
  ...createNestedVars("font-size", typographyPrimitives.fontSize ?? {}),
  ...createNestedVars("line-height", typographyPrimitives.lineHeight ?? {}),

  // Radius tokens — only the SEMANTIC layer is emitted as utilities.
  // Primitives stay internal (consumed by semantic/radius.ts) so they neither
  // leak into the utility namespace nor override Tailwind's built-in `rounded-*`.
  ...createNestedVars("radius", semanticRadius),

  // Semantic color tokens
  ...createNestedVars("color", colors),

  // Semantic typography tokens
  ...buildTypographyTokens(),

  // Semantic shadow tokens
  ...createNestedVars("shadow", semanticShadow),
];

const cssContent = `/* GENERATED FILE - DO NOT EDIT MANUALLY
 * Generated by scripts/generate-css.ts
 */

@theme {
${themeVars.map((v) => `  ${v}`).join("\n")}
}
`;

const outputPath = path.join(process.cwd(), "src/styles/tokens.css");

try {
  const dir = path.dirname(outputPath);

  if (!fs.existsSync(dir)) {
    fs.mkdirSync(dir, { recursive: true });
  }

  fs.writeFileSync(outputPath, cssContent, "utf8");
  console.log("✅ Design tokens generated successfully →", outputPath);
} catch (err) {
  console.error("❌ Failed to generate tokens:", err);
  process.exit(1);
}
